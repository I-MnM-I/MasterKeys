#!/usr/bin/env python3
"""Turn the [KEY] section of a Redragon OemDrv KB.ini into a MasterKeys layout TOML.

Usage: kbini_to_layout.py <KB.ini> <out.toml>

Each [KEY] line looks like `K1=20,23,43,48, 0x02,0x1B,0x00,0`: the key's rectangle in the vendor's
picture (left, top, right, bottom), a type, the Windows virtual-key code, a second code and the LED
index. The comment line before it (`;Esc`) is the label.
"""

import sys

# Pixel distance between neighbouring key starts in the vendor picture (Q at 68, W at 101, ...).
PITCH = 32.4
# Pixels of gap between two keys, added back so a 1-unit key is 1 unit wide.
GAP = 9

# Windows virtual-key code -> Linux evdev code. 0xFA (Fn), 0xFD (keypad Enter), 0x8F (Mute) and
# 0x99 (Calculator) are the vendor's own codes for keys Windows has no VK for.
VK_TO_EVDEV = {
    0x1B: 1, 0x31: 2, 0x32: 3, 0x33: 4, 0x34: 5, 0x35: 6, 0x36: 7, 0x37: 8, 0x38: 9, 0x39: 10,
    0x30: 11, 0xBD: 12, 0xBB: 13, 0x08: 14, 0x09: 15,
    0x51: 16, 0x57: 17, 0x45: 18, 0x52: 19, 0x54: 20, 0x59: 21, 0x55: 22, 0x49: 23, 0x4F: 24,
    0x50: 25, 0xDB: 26, 0xDD: 27, 0x0D: 28, 0xA2: 29,
    0x41: 30, 0x53: 31, 0x44: 32, 0x46: 33, 0x47: 34, 0x48: 35, 0x4A: 36, 0x4B: 37, 0x4C: 38,
    0xBA: 39, 0xDE: 40, 0xC0: 41, 0xA0: 42, 0xDC: 43,
    0x5A: 44, 0x58: 45, 0x43: 46, 0x56: 47, 0x42: 48, 0x4E: 49, 0x4D: 50, 0xBC: 51, 0xBE: 52,
    0xBF: 53, 0xA1: 54, 0x6A: 55, 0xA4: 56, 0x20: 57, 0x14: 58,
    0x70: 59, 0x71: 60, 0x72: 61, 0x73: 62, 0x74: 63, 0x75: 64, 0x76: 65, 0x77: 66, 0x78: 67,
    0x79: 68, 0x90: 69, 0x91: 70,
    0x67: 71, 0x68: 72, 0x69: 73, 0x6D: 74, 0x64: 75, 0x65: 76, 0x66: 77, 0x6B: 78,
    0x61: 79, 0x62: 80, 0x63: 81, 0x60: 82, 0x6E: 83, 0x7A: 87, 0x7B: 88,
    0xFD: 96, 0xA3: 97, 0x6F: 98, 0x2C: 99, 0xA5: 100,
    0x24: 102, 0x26: 103, 0x21: 104, 0x25: 105, 0x27: 106, 0x23: 107, 0x28: 108, 0x22: 109,
    0x2D: 110, 0x2E: 111, 0x8F: 113, 0x13: 119, 0x5B: 125, 0x5D: 127, 0x99: 140, 0xFA: 464,
}

# The two hotkeys right of Calculator carry tiny codes (0x1, 0x2) and no name in KB.ini.
HOTKEYS = {0x01: (148, "Hot 1"), 0x02: (149, "Hot 2")}

LEDS = 126


def parse(path):
    keys, label, in_keys = [], None, False
    with open(path, encoding="latin-1") as f:
        for raw in f:
            line = raw.strip()
            if line.startswith("["):
                in_keys = line == "[KEY]"
                continue
            if not in_keys or not line:
                continue
            if line.startswith(";"):
                label = line[1:].strip()
                continue
            if not line.startswith("K") or "=" not in line:
                continue
            fields = [p.strip() for p in line.split("=", 1)[1].split(",")]
            left, top, right, bottom = (int(v) for v in fields[:4])
            vk, led = int(fields[5], 16), int(fields[7], 0)
            keys.append((label or "?", left, top, right, bottom, vk, led))
            label = None
    return keys


def main(src, out):
    entries = parse(src)
    min_left = min(e[1] for e in entries)
    min_top = min(e[2] for e in entries)
    lines = [
        "# Redragon K745 PRO, generated by tools/redragon/kbini_to_layout.py from Redragon's KB.ini.",
        "# Units: 1 = one standard key. code = Linux evdev key code; led = index in the lighting frame.",
        "",
    ]
    written = 0
    for label, left, top, right, bottom, vk, led in entries:
        if vk in HOTKEYS:
            code, label = HOTKEYS[vk]
        elif vk in VK_TO_EVDEV:
            code = VK_TO_EVDEV[vk]
        else:
            print(f"skip {label}: no evdev code for VK 0x{vk:02X}", file=sys.stderr)
            continue
        if led >= LEDS:
            print(f"skip {label}: LED {led} outside the {LEDS}-LED frame", file=sys.stderr)
            continue
        x = round((left - min_left) / PITCH, 2)
        y = round((top - min_top) / PITCH, 2)
        w = round((right - left + GAP) / PITCH, 2)
        h = round((bottom - top + GAP) / PITCH, 2)
        label = label.replace("\\", "\\\\").replace('"', '\\"')
        lines += ["[[key]]", f"code = {code}", f'label = "{label}"', f"x = {x}", f"y = {y}", f"w = {w}",
                  f"h = {h}", f"led = {led}", ""]
        written += 1
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {written} keys to {out}", file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
